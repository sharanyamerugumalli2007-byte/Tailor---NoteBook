-- Tailor Notebook schema (PostgreSQL 13+)
-- Run: psql -U postgres -d tailor_notebook -f database/schema.sql

DROP TABLE IF EXISTS notifications, order_status_history, order_items, orders,
  appointments, measurements, customers, users CASCADE;

CREATE TABLE users (
  id            INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name          VARCHAR(100) NOT NULL,
  email         VARCHAR(150) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role          VARCHAR(20) NOT NULL DEFAULT 'staff' CHECK (role IN ('admin','staff')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE customers (
  id         INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name       VARCHAR(120) NOT NULL,
  phone      VARCHAR(20)  NOT NULL,
  email      VARCHAR(150),
  address    TEXT,
  gender     VARCHAR(10) CHECK (gender IN ('male','female','other')),
  notes      TEXT,
  deleted_at TIMESTAMPTZ,                 -- soft delete keeps order/measurement history intact
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_customers_name  ON customers (lower(name));
CREATE INDEX idx_customers_phone ON customers (phone);
CREATE INDEX idx_customers_email ON customers (lower(email));

CREATE TABLE measurements (
  id                 INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  customer_id        INTEGER NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  version            INTEGER NOT NULL CHECK (version > 0),
  unit               VARCHAR(5) NOT NULL DEFAULT 'in' CHECK (unit IN ('in','cm')),
  shoulder           NUMERIC(6,2) CHECK (shoulder     > 0),
  chest              NUMERIC(6,2) CHECK (chest        > 0),
  waist              NUMERIC(6,2) CHECK (waist        > 0),
  hip                NUMERIC(6,2) CHECK (hip          > 0),
  neck               NUMERIC(6,2) CHECK (neck         > 0),
  sleeve_length      NUMERIC(6,2) CHECK (sleeve_length> 0),
  armhole            NUMERIC(6,2) CHECK (armhole      > 0),
  shirt_length       NUMERIC(6,2) CHECK (shirt_length > 0),
  pant_length        NUMERIC(6,2) CHECK (pant_length  > 0),
  thigh              NUMERIC(6,2) CHECK (thigh        > 0),
  knee               NUMERIC(6,2) CHECK (knee         > 0),
  inseam             NUMERIC(6,2) CHECK (inseam       > 0),
  outseam            NUMERIC(6,2) CHECK (outseam      > 0),
  other_measurements TEXT,
  notes              TEXT,
  is_current         BOOLEAN NOT NULL DEFAULT TRUE,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (customer_id, version)
);
-- Exactly one current version per customer
CREATE UNIQUE INDEX uq_measurements_current ON measurements (customer_id) WHERE is_current;

CREATE TABLE orders (
  id                     INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
  customer_id            INTEGER NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
  measurement_id         INTEGER REFERENCES measurements(id) ON DELETE SET NULL,
  order_date             DATE NOT NULL DEFAULT CURRENT_DATE,
  expected_delivery_date DATE,
  total_amount           NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
  advance_amount         NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (advance_amount >= 0),
  remaining_amount       NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (remaining_amount >= 0),
  payment_status         VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                         CHECK (payment_status IN ('PENDING','PARTIALLY_PAID','PAID')),
  status                 VARCHAR(30) NOT NULL DEFAULT 'ORDER_RECEIVED'
                         CHECK (status IN ('ORDER_RECEIVED','MEASUREMENT_TAKEN','CUTTING','STITCHING',
                                           'TRIAL','READY','DELIVERED','CANCELLED')),
  notes                  TEXT,
  created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (advance_amount <= total_amount),
  CHECK (expected_delivery_date IS NULL OR expected_delivery_date >= order_date)
);
CREATE INDEX idx_orders_customer ON orders (customer_id);
CREATE INDEX idx_orders_status   ON orders (status);
CREATE INDEX idx_orders_delivery ON orders (expected_delivery_date);

CREATE TABLE order_items (
  id                   INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id             INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  item_type            VARCHAR(50) NOT NULL,
  description          TEXT,
  quantity             INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
  price                NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  special_instructions TEXT,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_order_items_order ON order_items (order_id);

CREATE TABLE order_status_history (
  id         INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id   INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  status     VARCHAR(30) NOT NULL,
  notes      TEXT,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_osh_order ON order_status_history (order_id, changed_at);

CREATE TABLE appointments (
  id               INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  customer_id      INTEGER NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  appointment_date DATE NOT NULL,
  appointment_time TIME NOT NULL,
  purpose          VARCHAR(20) NOT NULL
                   CHECK (purpose IN ('MEASUREMENT','TRIAL','DELIVERY','CONSULTATION','ALTERATION')),
  status           VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
                   CHECK (status IN ('SCHEDULED','COMPLETED','CANCELLED','RESCHEDULED')),
  notes            TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_appt_date ON appointments (appointment_date, appointment_time);
CREATE INDEX idx_appt_customer ON appointments (customer_id);
-- One active booking per time slot (shop is single-chair); the API also checks and returns a friendly 409
CREATE UNIQUE INDEX uq_appt_slot ON appointments (appointment_date, appointment_time)
  WHERE status IN ('SCHEDULED','RESCHEDULED');

CREATE TABLE notifications (
  id         INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title      VARCHAR(150) NOT NULL,
  message    TEXT NOT NULL,
  type       VARCHAR(30) NOT NULL DEFAULT 'INFO',
  is_read    BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_notif_user ON notifications (user_id, is_read, created_at DESC);
